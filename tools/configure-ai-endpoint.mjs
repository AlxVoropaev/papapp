import { readFile, writeFile } from 'node:fs/promises';
const input = process.argv[2];
if (!input) throw new Error('Usage: node tools/configure-ai-endpoint.mjs https://NAME.SUBDOMAIN.workers.dev/suggest');
const endpoint = new URL(input);
if (endpoint.protocol !== 'https:' || !/^[a-z0-9.-]+\.workers\.dev$/.test(endpoint.hostname) || endpoint.pathname !== '/suggest' || endpoint.search || endpoint.hash || endpoint.username || endpoint.password || endpoint.port) throw new Error('Expected a HTTPS workers.dev /suggest endpoint.');
const androidPath = 'android/app/src/main/res/values/strings.xml';
const android = await readFile(androidPath, 'utf8');
const androidEndpoint = /(<string name="tags_endpoint" translatable="false">)[^<]*(<\/string>)/;
if (!androidEndpoint.test(android)) throw new Error('Missing Android tag endpoint resource.');
await writeFile(androidPath, android.replace(androidEndpoint, `$1${endpoint.href}$2`));
console.log('AI endpoint configured: ' + endpoint.origin);
